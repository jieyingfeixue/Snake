void usart1_send_byte(uint8_t b)
{
	while (USART_GetFlagStatus(USART1, USART_FLAG_TXE) == RESET);
	USART_SendData(USART1, b);
}

void usart1_send_str(const char *s)
{
	while (*s) usart1_send_byte((uint8_t)*s++);
}
