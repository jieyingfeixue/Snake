static uint8_t adc_ch_to_col(uint8_t ch)
{
  if (ch == ADC_Channel_3) return 0;
  if (ch == ADC_Channel_6) return 1;
  if (ch == ADC_Channel_7) return 2;
  if (ch == ADC_Channel_16) return 3;
  if (ch == ADC_Channel_17) return 4;
  return 0;
}

int Read_ADC1_MultiChannel(u8 channNo)
{
  uint8_t col = adc_ch_to_col((uint8_t)channNo);
  uint32_t sum = 0;
  uint8_t i;

  for (i = 0; i < SampleNum; i++) {
    sum += ADC_ConvertedValue[i][col];
  }
  return (int)(sum / SampleNum);
}

/* potentiometer on ADC1 ch3 (PA3), smoothed 0..100% */
uint8_t pot_read_volume_pct(void)
{
  static uint16_t smooth = 0;
  uint16_t raw;
  uint8_t vol;

  raw = (uint16_t)Read_ADC1_MultiChannel(ADC_Channel_3);
  if (smooth == 0) {
    smooth = raw;
  } else {
    smooth = (uint16_t)((smooth * 7u + raw) / 8u);
  }

  vol = (uint8_t)(((uint32_t)smooth * 100u) / 4095u);
  if (vol > 100) vol = 100;
  return vol;
}

